/**
 * The copyable budget memo the runway planner offers once its figures are in.
 *
 * Pulled out of the panel so it can be tested without a DOM. Each source line
 * prints the reading with its own unit: the memo used to append "%" to every
 * value, and the BBB spread is stored in basis points, so a memo written to be
 * taken to a board read "174.00%" for a 1.74-point spread. A missing reading
 * printed "N/A%".
 */
import { formatNumberWithUnit } from "../../../lib/formatters";
import type { RegimeAssessment } from "../../../lib/regimeEngine";
import { getRegimePublicLabel } from "../../../lib/regimePresentation";
import { paceLabel } from "../../../lib/report/paceLabels";
import type { buildRunwayPlan, RunwayPlannerRequest } from "../../../lib/report/runwayPlanner";
import type { MacroSeriesReading, SensorReading } from "../../../lib/types";

const usd = new Intl.NumberFormat("en-US", { style: "currency", currency: "USD", maximumFractionDigits: 0 });

const readingValue = (reading: SensorReading | MacroSeriesReading | undefined) =>
  reading && reading.value !== null ? formatNumberWithUnit(reading.value, reading.unit) : "not available this week";

export const buildBudgetMemoMarkdown = ({
  assessment,
  sensors = [],
  macroSeries = [],
  recordDateLabel,
  output,
  request,
  growthAssumedFlat,
  paybackStrictness,
  stageLabel,
  sectorLabel,
}: {
  assessment: RegimeAssessment;
  sensors?: readonly SensorReading[];
  macroSeries?: readonly MacroSeriesReading[];
  recordDateLabel: string;
  output: ReturnType<typeof buildRunwayPlan>;
  request: RunwayPlannerRequest;
  growthAssumedFlat: boolean;
  paybackStrictness: { level: number; label: string };
  stageLabel: string;
  sectorLabel: string;
}) => {
  const sensor = (id: SensorReading["id"]) => readingValue(sensors.find((reading) => reading.id === id));
  const macro = (id: MacroSeriesReading["id"]) => readingValue(macroSeries.find((reading) => reading.id === id));
  const conditions = getRegimePublicLabel(assessment.regime);
  const pace = paceLabel(assessment.policyAssessment.posture).toLowerCase();

  return `
# Budget memo: planning against this week's guidance
**Date**: ${recordDateLabel}
**Conditions**: ${conditions} · Pace: ${pace}

## 1. Summary
Whether reads current conditions as **${conditions}**. On U.S. credit conditions and investor appetite, the pace this sets is **${pace}**.

This memo lines the budget and spending limits up with those conditions:
- **Runway risk**: ${output.runwayRisk.summary}
- **When to raise**: ${output.raiseTimingWindow.summary}
- **How far burn can move**: ${output.burnAdjustmentRange.summary}
- **Payback bar**: ${paybackStrictness.label.toLowerCase()} (${paybackStrictness.level} of 3).

## 2. Our Inputs
- **Runway**: ${request.runway} months
- **Monthly burn**: ${usd.format(request.burn)}
- **Monthly revenue**: ${usd.format(request.revenue)}
- **Monthly revenue growth**: ${growthAssumedFlat ? "not entered; assumed flat" : `${request.growthRate}%`}
- **Stage / sector**: ${stageLabel} · ${sectorLabel}

## 3. The rules this sets
- **Fundraising**: ${output.boundedRules.capitalRaising}
- **Spending**: ${output.boundedRules.burnDiscipline}

## 4. Sources
- **Short-term borrowing rate**: ${sensor("BASE_RATE")} (Source: US Treasury)
- **Recession warning gauge (10-year minus 2-year)**: ${sensor("CURVE_SLOPE")} (Source: US Treasury)
- **Corporate borrowing premium**: ${macro("BBB_CREDIT_SPREAD")}, the extra interest mid-grade companies pay over the government (Source: St. Louis Fed, Moody's BBB corporate bond yield minus the 10-year Treasury)
- **Inflation, year over year**: ${macro("CPI_YOY")} (Source: Bureau of Labor Statistics, consumer price index)
- **Unemployment rate**: ${macro("UNEMPLOYMENT_RATE")} (Source: Bureau of Labor Statistics)

---
*Generated by Whether from the figures entered in the runway planner. Check the inputs above before circulating.*
`.trim();
};
