/**
 * Copies the premise test's registration and results into
 * lib/research/premiseTestDocs.ts, which the two /research/*.md routes serve.
 *
 * The repository is private, so a link from /trust to the files on GitHub is a
 * 404 for every reader. The routes run on the edge, which has no filesystem,
 * so the text is bundled as a module instead of read at request time.
 *
 *   bun scripts/research/publishPremiseTestDocs.ts          write the module
 *   bun scripts/research/publishPremiseTestDocs.ts --check  fail if it differs from the docs
 */
import { readFileSync, writeFileSync } from "node:fs";

const MODULE_PATH = "lib/research/premiseTestDocs.ts";

const SOURCES = {
  registration: "docs/research/premise-test-preregistration.md",
  results: "docs/research/premise-test-results.md",
} as const;

const render = () => {
  const entries = Object.entries(SOURCES).map(
    ([key, path]) => `  /** ${path} */\n  ${key}: ${JSON.stringify(readFileSync(path, "utf8"))},`,
  );
  return [
    "// Generated by scripts/research/publishPremiseTestDocs.ts from docs/research/. Do not edit;",
    "// edit the docs and rerun the script. tests/premiseTestDocs.test.ts fails when they differ.",
    "export const PREMISE_TEST_DOCS = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
};

const next = render();
if (process.argv.includes("--check")) {
  if (readFileSync(MODULE_PATH, "utf8") !== next) {
    console.error(`[premise-docs] ${MODULE_PATH} differs from docs/research/. Run bun scripts/research/publishPremiseTestDocs.ts.`);
    process.exit(1);
  }
  console.log(`[premise-docs] ${MODULE_PATH} matches docs/research/.`);
} else {
  writeFileSync(MODULE_PATH, next);
  console.log(`[premise-docs] wrote ${MODULE_PATH}`);
}
