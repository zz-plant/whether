/**
 * Copies research documents from docs/research/ into the lib/research/ modules that the
 * /research/*.md routes serve: the premise test's registration and results, and the advice
 * corpus's pre-registration and results.
 *
 * The repository is private, so a link from the site to the files on GitHub is a 404 for
 * every reader. The routes run on the edge, which has no filesystem, so the text is bundled
 * as a module instead of read at request time.
 *
 *   bun scripts/research/publishResearchDocs.ts          write the modules
 *   bun scripts/research/publishResearchDocs.ts --check  fail if any differs from the docs
 */
import { readFileSync, writeFileSync } from "node:fs";

const MODULES = [
  {
    path: "lib/research/premiseTestDocs.ts",
    name: "PREMISE_TEST_DOCS",
    test: "tests/premiseTestDocs.test.ts",
    sources: {
      registration: "docs/research/premise-test-preregistration.md",
      results: "docs/research/premise-test-results.md",
    },
  },
  {
    path: "lib/research/adviceCorpusDocs.ts",
    name: "ADVICE_CORPUS_DOCS",
    test: "tests/adviceCorpusDocs.test.ts",
    sources: {
      registration: "docs/research/advice-corpus-preregistration.md",
      results: "docs/research/advice-corpus-results.md",
      note: "docs/research/2026-10-31-advice-corpus-null-result.md",
    },
  },
] as const;

const render = (entry: (typeof MODULES)[number]) => {
  const entries = Object.entries(entry.sources).map(
    ([key, path]) => `  /** ${path} */\n  ${key}: ${JSON.stringify(readFileSync(path, "utf8"))},`,
  );
  return [
    "// Generated by scripts/research/publishResearchDocs.ts from docs/research/. Do not edit;",
    `// edit the docs and rerun the script. ${entry.test} fails when they differ.`,
    `export const ${entry.name} = {`,
    ...entries,
    "} as const;",
    "",
  ].join("\n");
};

const check = process.argv.includes("--check");
let stale = 0;
for (const entry of MODULES) {
  const next = render(entry);
  if (check) {
    if (readFileSync(entry.path, "utf8") !== next) {
      console.error(`[research-docs] ${entry.path} differs from docs/research/. Run bun scripts/research/publishResearchDocs.ts.`);
      stale += 1;
    }
  } else {
    writeFileSync(entry.path, next);
    console.log(`[research-docs] wrote ${entry.path}`);
  }
}
if (check) {
  if (stale > 0) process.exit(1);
  console.log("[research-docs] every module matches docs/research/.");
}
